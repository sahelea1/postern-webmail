export type Key = keyof Dict;
const activeLang = signal<"en" | "de">("en");

export function setLanguage(pref: string) {
  const lang = pref === "auto" ? (navigator.language || "en").slice(0, 2).toLowerCase() : pref;
  activeLang.value = lang === "de" ? "de" : "en";
  document.documentElement.lang = activeLang.value;
}

export function t(key: Key, ...args: (string | number)[]): string {
  const active: Partial<Dict> = activeLang.value === "de" ? de : en;
  let s: string = active[key] ?? en[key];
  args.forEach((a, i) => {
    s = s.replace(`{${i}}`, String(a));
  });
  return s;
}
